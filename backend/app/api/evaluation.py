"""Controlled-test evidence log: manual monitoring vs GlobalEye.

Stores ONLY trials that a human recorded after running a real test. Nothing is seeded or generated; with no
trials the summary reports ``n = 0``. Medians are computed from the recorded rows only.
"""
import json
import statistics
import threading
from typing import Any, Dict, List, Literal, Optional

from fastapi import APIRouter, Depends
from pydantic import BaseModel, ConfigDict, Field

from app.api.deps import current_actor
from app.config import get_settings
from app.database import utcnow

router = APIRouter(prefix="/api/evaluation", tags=["evaluation"])
_lock = threading.Lock()


class TrialIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    arm: Literal["manual", "globaleye"]
    scenario: str = Field(..., min_length=2, max_length=120)
    detection_seconds: Optional[float] = Field(None, ge=0, le=86400, description="Event start -> first alert/notice")
    acknowledgement_seconds: Optional[float] = Field(None, ge=0, le=86400, description="Event start -> acknowledged")
    false_alarms: int = Field(0, ge=0, le=1000)
    missed: bool = False
    notes: Optional[str] = Field(None, max_length=500)


def _path():
    return get_settings().data_dir / "evaluation_trials.json"


def _load() -> List[Dict[str, Any]]:
    p = _path()
    if not p.is_file():
        return []
    try:
        return json.loads(p.read_text())
    except Exception:
        return []


def _summarise(trials: List[Dict[str, Any]]) -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    for arm in ("manual", "globaleye"):
        rows = [t for t in trials if t["arm"] == arm]
        det = [t["detection_seconds"] for t in rows if t.get("detection_seconds") is not None]
        ack = [t["acknowledgement_seconds"] for t in rows if t.get("acknowledgement_seconds") is not None]
        out[arm] = {
            "trials": len(rows),
            "median_detection_seconds": round(statistics.median(det), 1) if det else None,
            "median_acknowledgement_seconds": round(statistics.median(ack), 1) if ack else None,
            "false_alarms": sum(t.get("false_alarms", 0) for t in rows),
            "missed_incidents": sum(1 for t in rows if t.get("missed")),
        }
    return out


@router.get("/trials")
def list_trials() -> Dict[str, Any]:
    trials = _load()
    return {"trials": trials, "summary": _summarise(trials),
            "note": "Only human-recorded measurements. No data is generated by the system."}


@router.post("/trials", status_code=201)
def add_trial(body: TrialIn, actor: str = Depends(current_actor)) -> Dict[str, Any]:
    with _lock:
        trials = _load()
        row = body.model_dump()
        row.update(id=(max([t["id"] for t in trials], default=0) + 1), recorded_by=actor,
                   recorded_at=utcnow().isoformat())
        trials.append(row)
        get_settings().data_dir.mkdir(parents=True, exist_ok=True)
        _path().write_text(json.dumps(trials, indent=2))
    return {"trials": trials, "summary": _summarise(trials)}


@router.delete("/trials")
def clear_trials(actor: str = Depends(current_actor)) -> Dict[str, Any]:
    with _lock:
        _path().unlink(missing_ok=True)
    return {"trials": [], "summary": _summarise([])}
